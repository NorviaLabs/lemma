"""Download a lesson as one self-contained HTML file that works offline and sends nothing anywhere."""

from __future__ import annotations

import base64
import html
import json
import re
from importlib import resources

SCRIPTS = ("expr.js", "kernels.js", "visuals.js", "activities.js", "player.js")

# connect-src 'none' and form-action 'none': the page cannot send the learner's answers anywhere.
CSP = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; font-src data:; connect-src 'none'; form-action 'none'; base-uri 'none'"

# Every face the lesson uses is embedded, so the offline file looks the same without a network.
EMBEDDED_FONTS = ("archivo-latin-normal.woff2", "spline-sans-mono-latin-normal.woff2")

BOOT = """
LemmaPlayer.mount(document.getElementById("main"), JSON.parse(document.getElementById("lesson-data").textContent), {});
"""


def _static(name: str) -> str:
    return resources.files("lemma").joinpath("static", name).read_text(encoding="utf-8")


def _logo() -> str:
    """The OpenLemma mark, inline, so the offline file shows it with no request."""
    return _static("logo.svg").strip().replace('<svg xmlns="http://www.w3.org/2000/svg"', '<svg class="logo" aria-hidden="true"', 1)


def _favicon() -> str:
    return "data:image/svg+xml;base64," + base64.b64encode(_static("favicon.svg").strip().encode()).decode()


def _styles_with_embedded_fonts() -> str:
    """styles.css with its font files inlined as data: URIs, so the downloaded lesson needs no network."""
    css = _static("styles.css")
    fonts = resources.files("lemma").joinpath("static", "fonts")

    def inline(m):
        name = m.group(1)
        if name not in EMBEDDED_FONTS:
            return "url(\"data:font/woff2;base64,\")"  # dropped: the browser falls back to the next font
        data = base64.b64encode(fonts.joinpath(name).read_bytes()).decode()
        return f'url("data:font/woff2;base64,{data}")'

    return re.sub(r'url\("fonts/([A-Za-z0-9_.-]+)"\)', inline, css)


def _script_safe(text: str) -> str:
    return text.replace("</", "<\\/")


def lesson_html(lesson: dict) -> str:
    data = {k: v for k, v in lesson.items() if k not in ("plan",)}
    payload = json.dumps(data, ensure_ascii=False).replace("<", "\\u003c")  # "<" only occurs inside JSON strings
    scripts = "\n".join(f"<script>\n{_script_safe(_static(n))}\n</script>" for n in SCRIPTS)
    title = html.escape(lesson.get("title") or "OpenLemma lesson")
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="color-scheme" content="light">
<meta http-equiv="Content-Security-Policy" content="{CSP}">
<meta name="generator" content="OpenLemma">
<link rel="icon" href="{_favicon()}">
<title>{title}</title>
<style>
{_styles_with_embedded_fonts()}
</style>
</head>
<body>
<header class="site-head">
  <span class="wordmark">{_logo()}<span class="wm-name"><span class="wm-open">Open</span>Lemma</span></span>
</header>
<main id="main" tabindex="-1"></main>
<footer class="site-foot">
  <p>An offline OpenLemma lesson. It works without an internet connection and sends nothing anywhere, including your answers.
  Lessons are generated by AI and can contain errors, so check them against the source.</p>
</footer>
<script type="application/json" id="lesson-data">{payload}</script>
{scripts}
<script>{BOOT}</script>
</body>
</html>
"""
